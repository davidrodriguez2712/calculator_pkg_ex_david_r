class Calculator:
    def __init__(self):
        print("HELLO")

    def add(self, num1, num2):
        return num1 + num2
    
    def substract(self, num1, num2):
        return num1 - num2

    def multiply(self, num1, num2):
        return num1 * num2

    def divide(self, num1, num2):
        return num1 / num2